create or replace function public.gn24_daily_compute(p_date date)
returns jsonb language plpgsql security definer set search_path=public as $$
declare
  domestic text[] := array['seoul','busan','daegu','incheon','gwangju','daejeon','ulsan','sejong','gyeonggi','gangwon','chungbuk','chungnam','jeonbuk','jeonnam','gyeongbuk','gyeongnam','jeju'];
  registered text[];
  countries text[];
  v jsonb;
begin
  if not public.is_gn24_admin() then raise exception 'ADMIN_REQUIRED'; end if;
  if exists(select 1 from public.gn24_daily_records where record_date=p_date and status='locked') then raise exception 'DAILY_RECORD_LOCKED'; end if;
  if p_date is null or p_date > (now() at time zone 'Asia/Seoul')::date then raise exception 'INVALID_RECORD_DATE'; end if;
  select array_agg(distinct lower(m[1])) into registered
  from pg_constraint c
  cross join lateral regexp_matches(pg_get_constraintdef(c.oid),E'''([^'']+)''(?:::text)?','g') m
  where c.conrelid='public.gn24_articles'::regclass
    and c.contype='c'
    and pg_get_constraintdef(c.oid) ilike '%region_code%';
  if registered is null or not(domestic <@ registered) then raise exception 'REGION_REGISTRY_UNAVAILABLE'; end if;
  select array_agg(code order by code) into countries
  from unnest(registered) code
  where not(code=any(domestic));
  with a as (
    select nullif(lower(btrim(region_code)),'') code from public.gn24_articles
    where is_published=true and workflow_status='published' and visibility_scope='public' and date=p_date
  ), total as (select count(*)::int n from public.gn24_articles where is_published=true and workflow_status='published' and visibility_scope='public'),
  grouped as (select code,count(*)::int n from a group by code)
  select jsonb_build_object(
    'record_date',p_date,'news_count',(select count(*) from a),
    'domestic_news_count',(select count(*) from a where code=any(domestic)),
    'global_news_count',(select count(*) from a where code=any(countries)),
    'active_region_count',(select count(*) from grouped where code=any(domestic)),
    'active_country_count',(select count(*) from grouped where code=any(countries)),
    'unknown_count',(select count(*) from a where code is null or not(code=any(domestic)) and not(code=any(countries))),
    'total_articles',(select n from total),
    'regions',coalesce((select jsonb_agg(jsonb_build_object('code',code,'count',n) order by n desc,code) from grouped where code=any(domestic)),'[]'::jsonb),
    'countries',coalesce((select jsonb_agg(jsonb_build_object('code',code,'count',n) order by n desc,code) from grouped where code=any(countries)),'[]'::jsonb),
    'unknown',coalesce((select jsonb_agg(jsonb_build_object('code',code,'count',n) order by n desc,code) from grouped where code is null or not(code=any(domestic)) and not(code=any(countries))),'[]'::jsonb),
    'total_global_editions',array_length(countries,1),'total_korea_regions',array_length(domestic,1)
  ) into v;
  return v;
end $$;
revoke all on function public.gn24_daily_compute(date) from public,anon;
grant execute on function public.gn24_daily_compute(date) to authenticated;

create or replace function public.gn24_daily_publish(p_date date)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v jsonb; r public.gn24_daily_records; prev numeric; val numeric; k text;
begin
  if not public.is_gn24_admin() then raise exception 'ADMIN_REQUIRED'; end if;
  perform pg_advisory_xact_lock(hashtext('gn24_daily:'||p_date::text));
  if exists(select 1 from public.gn24_daily_records where record_date=p_date and status='locked') then raise exception 'DAILY_RECORD_LOCKED'; end if;
  if exists(select 1 from public.gn24_daily_records where record_date=p_date and status in ('published','archived')) then
    return (select jsonb_build_object('id',id,'status',status,'published_at',published_at,'already_published',true) from public.gn24_daily_records where record_date=p_date);
  end if;
  v:=public.gn24_daily_compute(p_date);
  insert into public.gn24_daily_records(record_date,news_count,domestic_news_count,global_news_count,active_country_count,active_region_count,status,published_at,updated_at)
  values(p_date,(v->>'news_count')::int,(v->>'domestic_news_count')::int,(v->>'global_news_count')::int,(v->>'active_country_count')::int,(v->>'active_region_count')::int,'published',now(),now())
  on conflict(record_date) do update set news_count=excluded.news_count,domestic_news_count=excluded.domestic_news_count,global_news_count=excluded.global_news_count,active_country_count=excluded.active_country_count,active_region_count=excluded.active_region_count,status=case when gn24_daily_records.status='locked' then 'locked' else 'published' end,published_at=coalesce(gn24_daily_records.published_at,now()),updated_at=now()
  returning * into r;
  update public.gn24_daily_records set
    milestone_count=(select count(*) from public.gn24_daily_events where daily_record_id=r.id and importance in ('IMPORTANT','HISTORIC')),
    development_count=(select count(*) from public.gn24_daily_events where daily_record_id=r.id and event_type='DEVELOPMENT')
  where id=r.id returning * into r;
  insert into public.gn24_daily_snapshots(record_date,daily_record_id,total_articles,daily_articles,total_global_editions,active_global_editions,total_korea_regions,active_korea_regions,total_countries,country_breakdown,region_breakdown,unknown_breakdown)
  values(p_date,r.id,(v->>'total_articles')::int,(v->>'news_count')::int,(v->>'total_global_editions')::int,(v->>'active_country_count')::int,(v->>'total_korea_regions')::int,(v->>'active_region_count')::int,(v->>'total_global_editions')::int,v->'countries',v->'regions',v->'unknown')
  on conflict(record_date) do nothing;
  foreach k in array array['news_count','domestic_news_count','global_news_count','active_country_count','active_region_count','total_articles'] loop
    val=(v->>k)::numeric; select metric_value into prev from public.gn24_record_metrics where metric_key=k and metric_date<p_date order by metric_date desc limit 1;
    insert into public.gn24_record_metrics(metric_date,metric_key,metric_value,previous_value,change_value)
    values(p_date,k,val,prev,case when prev is null then null else val-prev end)
    on conflict(metric_date,metric_key) do update set metric_value=excluded.metric_value,previous_value=excluded.previous_value,change_value=excluded.change_value;
  end loop;
  return v||jsonb_build_object('id',r.id,'status',r.status,'published_at',r.published_at);
end $$;
revoke all on function public.gn24_daily_publish(date) from public,anon;
grant execute on function public.gn24_daily_publish(date) to authenticated;

create or replace function public.gn24_get_daily_record(p_date date default null)
returns jsonb language plpgsql stable security definer set search_path=public as $$
declare r public.gn24_daily_records; d date; out jsonb;
begin
  if p_date is not null and p_date>(now() at time zone 'Asia/Seoul')::date then return null; end if;
  select * into r from public.gn24_daily_records where status in ('published','locked','archived') and (p_date is null or record_date=p_date) order by record_date desc limit 1;
  if r.id is null then return null; end if; d=r.record_date;
  select jsonb_build_object(
    'record',jsonb_build_object('record_date',r.record_date,'headline',r.headline,'summary',r.summary,'publisher_note',r.publisher_note,'hero_image_url',r.hero_image_url,'news_count',r.news_count,'domestic_news_count',r.domestic_news_count,'global_news_count',r.global_news_count,'active_country_count',r.active_country_count,'active_region_count',r.active_region_count,'milestone_count',r.milestone_count,'development_count',r.development_count,'verification_status',r.verification_status,'status',r.status,'published_at',r.published_at),
    'events',coalesce((select jsonb_agg(jsonb_build_object('id',e.id,'event_date',e.event_date,'occurred_at',e.occurred_at,'event_type',e.event_type,'title',e.title,'description',e.description,'problem',e.problem,'action_taken',e.action_taken,'result',e.result,'importance',e.importance,'verification_status',e.verification_status,'history_candidate',e.history_candidate,'source_url',e.source_url,'image_url',e.image_url) order by e.display_order,e.created_at) from public.gn24_daily_events e where e.daily_record_id=r.id and e.is_public=true),'[]'::jsonb),
    'snapshot',(select to_jsonb(s)-'id'-'daily_record_id' from public.gn24_daily_snapshots s where s.daily_record_id=r.id),
    'previous_date',(select max(record_date) from public.gn24_daily_records where record_date<d and status in ('published','locked','archived')),
    'next_date',(select min(record_date) from public.gn24_daily_records where record_date>d and record_date<=(now() at time zone 'Asia/Seoul')::date and status in ('published','locked','archived'))
  ) into out; return out;
end $$;
revoke all on function public.gn24_get_daily_record(date) from public;
grant execute on function public.gn24_get_daily_record(date) to anon,authenticated;

