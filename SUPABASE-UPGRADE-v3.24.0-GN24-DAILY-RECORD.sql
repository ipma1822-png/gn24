-- GLOBAL NEWS24 v3.24.0 — GN24 DAILY RECORD V1
-- Article source of truth: gn24_articles.date + is_published + region_code.
-- The editorial date column is already a date (KST business date), so no UTC cast is used.

create extension if not exists pgcrypto;

create table if not exists public.gn24_daily_records (
  id uuid primary key default gen_random_uuid(),
  record_date date not null unique,
  headline text not null default '', summary text not null default '',
  publisher_note text, hero_image_url text,
  news_count integer, domestic_news_count integer, global_news_count integer,
  active_country_count integer, active_region_count integer,
  milestone_count integer not null default 0, development_count integer not null default 0,
  verification_status text not null default 'SYSTEM AUTO VERIFIED'
    check (verification_status in ('SYSTEM AUTO VERIFIED','ADMIN VERIFIED','HISTORY CANDIDATE')),
  next_action text,
  status text not null default 'draft' check (status in ('draft','published','locked','archived')),
  published_at timestamptz, locked_at timestamptz,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.gn24_daily_events (
  id uuid primary key default gen_random_uuid(),
  daily_record_id uuid not null references public.gn24_daily_records(id) on delete restrict,
  event_date date not null, occurred_at timestamptz, recorded_at timestamptz not null default now(),
  event_type text not null check (event_type in ('NEWS','EDITION','REGION','NETWORK','DEVELOPMENT','ORGANIZATION','PARTNERSHIP','AWARD','MILESTONE','SPECIAL')),
  title text not null, description text not null default '',
  problem text, action_taken text, result text,
  importance text not null default 'NORMAL' check (importance in ('NORMAL','IMPORTANT','HISTORIC')),
  verification_status text not null default 'ADMIN VERIFIED'
    check (verification_status in ('SYSTEM AUTO VERIFIED','ADMIN VERIFIED','HISTORY CANDIDATE')),
  history_level text not null default 'RECORD' check (history_level in ('RECORD','MILESTONE','HISTORY')),
  history_candidate boolean not null default false,
  evidence_grade text, evidence_type text check (evidence_type is null or evidence_type in ('DATABASE','ARTICLE','GIT','OFFICIAL DOCUMENT','ADMIN CONFIRMATION','EXTERNAL SOURCE')),
  evidence_reference text, source_url text, image_url text,
  is_public boolean not null default true, display_order integer not null default 0,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  constraint gn24_daily_history_candidate_guard check (history_level <> 'HISTORY' or history_candidate = true)
);

create table if not exists public.gn24_daily_snapshots (
  id uuid primary key default gen_random_uuid(), record_date date not null unique,
  daily_record_id uuid not null unique references public.gn24_daily_records(id) on delete restrict,
  total_articles integer, daily_articles integer,
  total_global_editions integer, active_global_editions integer,
  total_korea_regions integer, active_korea_regions integer,
  total_countries integer, network_members integer, reporters integer, branches integer,
  country_breakdown jsonb, region_breakdown jsonb, unknown_breakdown jsonb,
  snapshot_version text not null default '1.0', created_at timestamptz not null default now()
);

create table if not exists public.gn24_record_metrics (
  id bigint generated by default as identity primary key,
  metric_date date not null, metric_key text not null, metric_value numeric,
  previous_value numeric, change_value numeric, source_type text not null default 'DATABASE',
  created_at timestamptz not null default now(), unique(metric_date,metric_key)
);

create index if not exists gn24_articles_daily_record_idx on public.gn24_articles(date,region_code) where is_published=true;
create index if not exists gn24_daily_events_record_idx on public.gn24_daily_events(daily_record_id,display_order,created_at);

create or replace function public.gn24_daily_record_guard() returns trigger language plpgsql set search_path=public as $$
begin
  if old.status='locked' and new is distinct from old then raise exception 'DAILY_RECORD_LOCKED'; end if;
  new.updated_at:=now(); return new;
end $$;
drop trigger if exists gn24_daily_record_guard_trg on public.gn24_daily_records;
create trigger gn24_daily_record_guard_trg before update on public.gn24_daily_records for each row execute function public.gn24_daily_record_guard();

create or replace function public.gn24_daily_event_guard() returns trigger language plpgsql set search_path=public as $$
begin
  if exists(select 1 from public.gn24_daily_records where id=new.daily_record_id and status='locked') then raise exception 'DAILY_RECORD_LOCKED'; end if;
  new.updated_at:=now(); return new;
end $$;
drop trigger if exists gn24_daily_event_guard_trg on public.gn24_daily_events;
create trigger gn24_daily_event_guard_trg before insert or update on public.gn24_daily_events for each row execute function public.gn24_daily_event_guard();

